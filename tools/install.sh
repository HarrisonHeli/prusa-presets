#!/usr/bin/env bash
# Link this machine's PrusaSlicer presets to the git preset repo and install
# the sync launcher.  Run from a clone:  ./tools/install.sh [--dry-run]
#
# Safe to re-run. Existing local presets are merged into the repo (never
# overwriting); same name + different content => "<name> (<host>).ini".
# Originals kept as *.pre-git.<stamp>, plus a tarball in ~/tmp.
set -euo pipefail

REPO="$(cd "$(dirname "$(readlink -f "$0")")/.." && pwd)"
DIRS=(print filament printer physical_printer sla_print sla_material)
DRY=0; [[ "${1:-}" == "--dry-run" ]] && DRY=1
run() { if ((DRY)); then echo "  [dry] $*"; else "$@"; fi; }
HOST="$(hostname -s)"

if pgrep -f '[/]prusa-slicer' >/dev/null; then
  echo "PrusaSlicer is running - close it first." >&2; exit 1
fi

# git filter: drop the "on <date> at <time> UTC" stamp PrusaSlicer writes on
# line 1 of every preset, so saves don't create noise diffs / conflicts.
run git -C "$REPO" config filter.prusa-stamp.clean "sed -E '1s/^(# generated by PrusaSlicer [^ ]+) on .*/\\1/'"
run git -C "$REPO" config filter.prusa-stamp.smudge cat
run git -C "$REPO" config pull.rebase true
git -C "$REPO" config user.name >/dev/null || run git -C "$REPO" config user.name "$USER@$HOST"
git -C "$REPO" config user.email >/dev/null || run git -C "$REPO" config user.email "$USER@$HOST.local"

CANDS=(
  "$HOME/.var/app/com.prusa3d.PrusaSlicer/config/PrusaSlicer"
  "${XDG_CONFIG_HOME:-$HOME/.config}/PrusaSlicer"
)
FOUND=0; stamp=$(date +%Y%m%d-%H%M%S)
for C in "${CANDS[@]}"; do
  [[ -d "$C" ]] || continue
  FOUND=1; echo "== $C"
  run mkdir -p "$HOME/tmp"
  run tar czhf "$HOME/tmp/prusaslicer-$(basename "$(dirname "$C")")-backup-$stamp.tgz" -C "$(dirname "$C")" "$(basename "$C")"
  for d in "${DIRS[@]}"; do
    src="$C/$d"; dst="$REPO/$d"
    run mkdir -p "$dst"
    if [[ -L "$src" ]]; then
      if [[ "$(readlink -f "$src")" == "$(readlink -f "$dst")" ]]; then echo "  $d: already linked"; continue; fi
      old="$(readlink -f "$src")"; echo "  $d: was linked to $old — merging + relinking"
      run rm "$src"; run mkdir -p "$src.pre-git.$stamp"
      [[ -d "$old" ]] && run cp -a "$old/." "$src.pre-git.$stamp/"
      srcdata="$src.pre-git.$stamp"
    elif [[ -d "$src" ]]; then
      run mv "$src" "$src.pre-git.$stamp"; srcdata="$src.pre-git.$stamp"
    else srcdata=""; fi
    if [[ -n "$srcdata" && -d "$srcdata" ]] || ((DRY)); then
      shopt -s nullglob
      for f in "${srcdata:-$src}"/*.ini; do
        b=$(basename "$f")
        if [[ ! -e "$dst/$b" ]]; then run cp -a "$f" "$dst/"; echo "  $d: + $b"
        elif ! diff -q <(sed 1d "$f") <(sed 1d "$dst/$b") >/dev/null; then
          alt="${b%.ini} ($HOST).ini"; run cp -a "$f" "$dst/$alt"; echo "  $d: CONFLICT $b -> kept local as '$alt'"
        fi
      done
      shopt -u nullglob
    fi
    run ln -s "$dst" "$src"; echo "  $d: linked -> $dst"
  done
done
((FOUND)) || { echo "No PrusaSlicer config found. Start PrusaSlicer once (finish the wizard), close it, re-run." >&2; exit 1; }

# Launcher: ~/.local/bin + a desktop entry that shadows the system/Flatpak one
run mkdir -p "$HOME/.local/bin" "$HOME/.local/share/applications"
run ln -sfn "$REPO/tools/prusaslicer-sync" "$HOME/.local/bin/prusaslicer-sync"
DESK="$HOME/.local/share/applications/com.prusa3d.PrusaSlicer.desktop"
if ((DRY)); then echo "  [dry] write $DESK"; else
cat >"$DESK" <<EOF
[Desktop Entry]
Name=PrusaSlicer
GenericName=3D Printing Software (synced presets)
Icon=com.prusa3d.PrusaSlicer
Exec=$REPO/tools/prusaslicer-sync %U
Terminal=false
Type=Application
MimeType=model/stl;application/vnd.ms-3mfdocument;application/prs.wavefront-obj;application/x-amf;x-scheme-handler/prusaslicer;
Categories=Graphics;3DGraphics;Engineering;
Keywords=3D;Printing;Slicer;slice;3D;printer;convert;gcode;stl;obj;amf;SLA
StartupNotify=false
StartupWMClass=prusa-slicer
EOF
command -v update-desktop-database >/dev/null && update-desktop-database -q "$HOME/.local/share/applications" || true
fi
echo "Done. Launch PrusaSlicer from the menu (or run prusaslicer-sync). Log: ~/.local/state/prusa-presets.log"
